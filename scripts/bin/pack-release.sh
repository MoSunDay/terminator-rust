#!/usr/bin/env bash
# Pack the release tarball from target/release binaries.
#
# Usage: scripts/bin/pack-release.sh [triple]
#   triple  target triple baked into the artifact name
#          (default: the rustc host triple)
#
# Output under dist/:
#   terminator-rust-<version>-<triple>.tar.gz          deterministic archive
#   terminator-rust-<version>-<triple>.tar.gz.sha256   sidecar checksum
#
# Contents: bin/terminator-rust + bin/terminator-ctl, README.md,
# LICENSE-* when present, hicolor icon tree (Linux) or the .icns bundle
# (macOS). The archive is deterministic (sorted names, epoch mtime,
# zeroed owner, gzip -n) so identical inputs pack byte-identically -
# GNU tar is required (bsdtar lacks the flags; on macOS brew install
# gnu-tar and this script picks up gtar automatically).
set -euo pipefail
cd "$(dirname "$0")/../.."

fail() { echo "FAIL: $*" >&2; exit 1; }

sum256() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$@"
    else
        shasum -a 256 "$@"   # macOS default
    fi
}

VERSION=$(sed -n 's/^version *= *"\([^"]*\)" *$/\1/p' Cargo.toml | head -n1)
[ -n "$VERSION" ] || fail "cannot read workspace version from Cargo.toml"

TRIPLE=${1:-$(rustc -vV | sed -n 's/^host: //p')}
[ -n "$TRIPLE" ] || fail "cannot detect the host triple; pass one explicitly"

TAR_BIN=tar
if ! tar --version 2>/dev/null | grep -q 'GNU tar'; then
    command -v gtar >/dev/null 2>&1 \
        || fail "deterministic tar needs GNU tar (brew install gnu-tar on macOS)"
    TAR_BIN=gtar
fi

DIST=dist
DIRNAME="terminator-rust-$VERSION-$TRIPLE"
STAGE="$DIST/$DIRNAME"
TGZ="$DIST/$DIRNAME.tar.gz"

for f in target/release/terminator-rust target/release/terminator-ctl README.md; do
    [ -f "$f" ] || fail "$f missing (run cargo build --release first)"
done

rm -rf "$STAGE"
mkdir -p "$STAGE/bin"
install -m 0755 target/release/terminator-rust "$STAGE/bin/terminator-rust"
install -m 0755 target/release/terminator-ctl "$STAGE/bin/terminator-ctl"
install -m 0644 README.md "$STAGE/README.md"
for f in LICENSE-MIT LICENSE-APACHE; do
    [ -f "$f" ] && install -m 0644 "$f" "$STAGE/$f"
done

case "$TRIPLE" in
    *-darwin*)
        # assets/logo is generated by scripts/bin/gen-logo.py.
        [ -f assets/logo/terminator-rust.icns ] \
            || fail "assets/logo/terminator-rust.icns missing; run scripts/bin/gen-logo.py"
        mkdir -p "$STAGE/Resources"
        install -m 0644 assets/logo/terminator-rust.icns \
            "$STAGE/Resources/terminator-rust.icns"
        ;;
    *)
        [ -f assets/logo/icon-256.png ] \
            || fail "assets/logo/icon-256.png missing; run scripts/bin/gen-logo.py"
        for n in 16 32 48 128 256; do
            mkdir -p "$STAGE/share/icons/hicolor/${n}x${n}/apps"
            install -m 0644 "assets/logo/icon-${n}.png" \
                "$STAGE/share/icons/hicolor/${n}x${n}/apps/terminator-rust.png"
        done
        ;;
esac

# Deterministic archive: sorted names, zeroed mtime/owner, gzip -n
# (no timestamp) -> identical tarball for identical inputs.
"$TAR_BIN" -C "$DIST" --sort=name --mtime='UTC 1970-01-01' --owner=0 \
    --group=0 --numeric-owner -c "$DIRNAME" | gzip -n > "$TGZ"

(cd "$DIST" && sum256 "$DIRNAME.tar.gz" > "$DIRNAME.tar.gz.sha256")
(cd "$DIST" && sum256 -c "$DIRNAME.tar.gz.sha256") \
    || fail "freshly packed tarball failed its own checksum"

echo "packed $TGZ (+ .sha256)"
